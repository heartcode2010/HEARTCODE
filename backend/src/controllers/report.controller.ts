import { Response, NextFunction } from 'express';
import { AuthenticatedRequest } from '../middleware/auth.middleware';
import Scan from '../models/Scan';
import Vulnerability from '../models/Vulnerability';
import AIAnalysis from '../models/AIAnalysis';
import Report from '../models/Report';

export const exportReport = async (req: AuthenticatedRequest, res: Response, next: NextFunction) => {
  try {
    const { scanId, format } = req.body;

    if (!scanId || !format) {
      return res.status(400).json({ success: false, message: 'Scan ID and report format are required' });
    }

    if (!['html', 'md', 'json', 'csv'].includes(format)) {
      return res.status(400).json({ success: false, message: 'Invalid report format' });
    }

    const scan = await Scan.findById(scanId);
    if (!scan) {
      return res.status(404).json({ success: false, message: 'Scan record not found' });
    }

    const findings = await Vulnerability.find({ scanId });
    const aiRecord = await AIAnalysis.findOne({ scanId });

    const now = new Date().toLocaleString();
    const ts = Date.now();
    const fileName = `coded_report_${ts}.${format === 'md' ? 'md' : format}`;

    const severityToRisk: Record<string, string> = {
      'Critical': 'critical',
      'High': 'high',
      'Medium': 'medium',
      'Low': 'low',
      'Informational': 'info'
    };

    const counts = { critical: 0, high: 0, medium: 0, low: 0, info: 0 };
    findings.forEach(f => {
      const risk = severityToRisk[f.severity] || 'info';
      if (counts[risk as keyof typeof counts] !== undefined) counts[risk as keyof typeof counts]++;
    });

    let fileContent = '';
    let contentType = 'text/plain';

    if (format === 'md') {
      contentType = 'text/markdown';
      fileContent = `# CODED Security Scan Report\n\n`;
      fileContent += `**Target:** ${scan.url}\n**Scanned:** ${now}\n**Engine:** CODED v10 Static Analysis\n\n---\n\n`;
      
      if (!findings.length) {
        fileContent += `## ✅ No Findings\nNo obvious client-side vulnerabilities detected.\n`;
      } else {
        fileContent += `## Summary\n`;
        Object.keys(counts).forEach(k => {
          const val = counts[k as keyof typeof counts];
          if (val > 0) fileContent += `- **${k.toUpperCase()}**: ${val}\n`;
        });
        fileContent += `\n---\n\n## Findings\n\n`;
        findings.forEach((f, i) => {
          const risk = severityToRisk[f.severity] || 'info';
          fileContent += `### ${i + 1}. [${risk.toUpperCase()}] ${f.name}\n\n**Description:** ${f.description}\n\n`;
          if (f.evidence) fileContent += `**Evidence:**\n\`\`\`\n${f.evidence}\n\`\`\`\n\n`;
          if (f.remediation) fileContent += `**Recommendation:** ${f.remediation}\n\n`;
          fileContent += `---\n\n`;
        });
      }
      fileContent += `*Generated by CODED — Authorised white-box pentesting only.*\n`;
    } 
    
    else if (format === 'json') {
      contentType = 'application/json';
      const data = {
        target: scan.url,
        scanned: now,
        engine: 'CODED v10',
        summary: counts,
        findings: findings.map(f => ({
          risk: severityToRisk[f.severity] || 'info',
          name: f.name,
          description: f.description,
          evidence: f.evidence || null,
          recommendation: f.remediation || null,
        })),
        aiAnalysis: aiRecord ? { score: aiRecord.score, tools: aiRecord.tools } : null,
      };
      fileContent = JSON.stringify(data, null, 2);
    } 
    
    else if (format === 'csv') {
      contentType = 'text/csv';
      fileContent = 'Severity,Finding,Description,Evidence,Recommendation\n';
      if (!findings.length) {
        fileContent += 'INFO,No findings,No vulnerabilities detected,,\n';
      } else {
        findings.forEach(f => {
          const risk = severityToRisk[f.severity] || 'info';
          fileContent += [risk, f.name, f.description, f.evidence || '', f.remediation || '']
            .map(v => `"${String(v).replace(/"/g, '""')}"`)
            .join(',') + '\n';
        });
      }
    } 
    
    else if (format === 'html') {
      contentType = 'text/html';
      const riskColor: Record<string, string> = {
        critical: '#ff4466',
        high: '#e87040',
        medium: '#d4920a',
        low: '#3ecf6e',
        info: '#6699cc',
      };

      let rows = '';
      if (!findings.length) {
        rows = '<tr><td colspan="4" style="text-align:center;color:#3ecf6e;padding:20px;">✅ No vulnerabilities detected</td></tr>';
      } else {
        findings.forEach(f => {
          const risk = severityToRisk[f.severity] || 'info';
          const c = riskColor[risk] || '#aaa';
          rows += `<tr>
            <td><span style="background:${c}22;color:${c};border:1px solid ${c}44;border-radius:3px;padding:2px 8px;font-size:.7rem;font-weight:700;text-transform:uppercase;white-space:nowrap;">${risk}</span></td>
            <td style="font-weight:600;color:#e8e2e2;">${f.name}</td>
            <td style="color:#8a8080;font-size:.82rem;">${f.description}</td>
            <td style="color:#5a8a5a;font-size:.78rem;white-space:pre-wrap;font-family:monospace;">${f.remediation || '—'}</td>
          </tr>`;
        });
      }

      const summaryBadges = Object.keys(counts)
        .filter(k => counts[k as keyof typeof counts] > 0)
        .map(k => {
          const c = riskColor[k] || '#aaa';
          const val = counts[k as keyof typeof counts];
          return `<span style="background:${c}22;color:${c};border:1px solid ${c}44;border-radius:4px;padding:4px 10px;font-size:.72rem;font-weight:700;text-transform:uppercase;margin-right:6px;">${k}: ${val}</span>`;
        })
        .join('');

      fileContent = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>CODED Scan Report — ${scan.url}</title>
  <style>
    *{margin:0;padding:0;box-sizing:border-box}
    body{background:#0a0a0b;color:#e8e2e2;font-family:Inter,system-ui,sans-serif;padding:32px}
    h1{font-size:1.4rem;font-weight:900;letter-spacing:.08em;color:#e02840;margin-bottom:4px}
    h2{font-size:.72rem;text-transform:uppercase;letter-spacing:.18em;color:#3e3838;margin:28px 0 10px;font-weight:700}
    .meta{font-size:.78rem;color:#6e6868;margin-bottom:24px;line-height:2}
    .summary{display:flex;gap:8px;flex-wrap:wrap;margin-bottom:28px}
    table{width:100%;border-collapse:collapse;font-size:.82rem}
    th{text-align:left;padding:9px 12px;background:#141416;border-bottom:2px solid #5a1e28;font-size:.62rem;text-transform:uppercase;letter-spacing:.14em;color:#6e6868}
    td{padding:9px 12px;border-bottom:1px solid #1c1c1f;vertical-align:top}
    tr:hover td{background:#0f0f10}
    .footer{margin-top:28px;font-size:.68rem;color:#3e3838;border-top:1px solid #2a2a2e;padding-top:14px}
    @media print{body{background:#fff;color:#000}h1{color:#c00}table{font-size:.75rem}}
  </style>
</head>
<body>
  <h1>CODED — Security Scan Report</h1>
  <div class="meta">
    <strong>Target:</strong> ${scan.url}<br>
    <strong>Scanned:</strong> ${now}<br>
    <strong>Engine:</strong> CODED v10 Static Analysis
  </div>
  <h2>Summary</h2>
  <div class="summary">${summaryBadges}</div>
  <h2>Findings (${findings.length})</h2>
  <table>
    <tr><th>Severity</th><th>Finding</th><th>Description</th><th>Recommendation</th></tr>
    ${rows}
  </table>
  <div class="footer">Generated by CODED &mdash; Authorised white-box pentesting only. Print this page (Ctrl+P) to save as PDF.</div>
</body>
</html>`;
    }

    // Log the generated report to MongoDB history
    if (req.user) {
      const report = new Report({
        scanId,
        userId: req.user.id,
        format,
        fileName,
      });
      await report.save();
    }

    res.setHeader('Content-disposition', `attachment; filename=${fileName}`);
    res.setHeader('Content-type', contentType);
    return res.send(fileContent);
  } catch (error) {
    next(error);
  }
};
export default { exportReport };
